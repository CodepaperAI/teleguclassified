  created_at timestamptz default now(),
  unique(listing_id, buyer_id, seller_id)
);

create table if not exists public.chat_messages (
  id uuid default gen_random_uuid() primary key,
  room_id uuid references chat_rooms(id) on delete cascade not null,
  sender_id uuid references auth.users(id) not null,
  content text not null,
  message_type text default 'text',
  file_url text,
  file_name text,
  file_size bigint,
  is_read boolean default false,
  created_at timestamptz default now()
);

-- RLS for Chat System
alter table chat_rooms enable row level security;
alter table chat_messages enable row level security;

-- Chat Rooms: Only participants can view their rooms
create policy "Users can view their own chat rooms" on chat_rooms
  for select using (auth.uid() = buyer_id or auth.uid() = seller_id);

create policy "Users can create chat rooms" on chat_rooms
  for insert with check (auth.uid() = buyer_id);

-- Chat Messages: Only participants of the room can view/insert messages
create policy "Users can view messages in their rooms" on chat_messages
  for select using (
    exists (
      select 1 from chat_rooms
      where id = chat_messages.room_id
      and (buyer_id = auth.uid() or seller_id = auth.uid())
    )
  );

create policy "Users can send messages in their rooms" on chat_messages
  for insert with check (
    auth.uid() = sender_id and
    exists (
      select 1 from chat_rooms
      where id = chat_messages.room_id
      and (buyer_id = auth.uid() or seller_id = auth.uid())
    )
  );

