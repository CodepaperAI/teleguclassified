  item_condition text, -- new, used, etc
  
  -- Contact Info
  contact_name text,
  contact_phone text,
  contact_email text,
  hide_phone_on_ad boolean default false,
  
  -- Location
  city text,
  postal_code text,
  latitude numeric,
  longitude numeric,
  
  -- Ownership
  user_id uuid references auth.users(id),
  
  -- Content & Media
  images text[],
  tags text[],
  youtube_video_url text,
  website_url text,
  
  -- Dynamic attributes (bedrooms, kilometers, salary range)
  attributes jsonb default '{}'::jsonb,
  
  -- System Fields
  boost_plan text,
  status text default 'active', -- active, sold, expired
  created_at timestamptz default now(),
  updated_at timestamptz default now()
